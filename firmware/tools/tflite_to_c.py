#!/usr/bin/env python3
"""
Convert any .tflite file into the firmware's model files
(only needed if ../training did not already export model_data.h/.cc).

  python tools/tflite_to_c.py ../training/models/model_int8.tflite

Writes include/model_data.h and src/model_data.cc with symbols
g_model_data[] (16-byte aligned) and g_model_data_len.
model_config.h (scaler mean/std/clip, quant params, threshold) must still
come from ../training/models/autoencoder/model_config.h.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if len(sys.argv) != 2:
    sys.exit(__doc__)
data = open(sys.argv[1], "rb").read()
with open(os.path.join(ROOT, "include", "model_data.h"), "w", newline="\n") as f:
    f.write("#pragma once\n#include <cstdint>\n\n"
            "extern const unsigned char g_model_data[];\n"
            "extern const unsigned int g_model_data_len;\n")
rows = ["  " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ","
        for i in range(0, len(data), 12)]
with open(os.path.join(ROOT, "src", "model_data.cc"), "w", newline="\n") as f:
    f.write("// Generated by tools/tflite_to_c.py from %s\n" % os.path.basename(sys.argv[1]))
    f.write("#include \"model_data.h\"\n\nalignas(16) const unsigned char g_model_data[] = {\n")
    f.write("\n".join(rows))
    f.write("\n};\nconst unsigned int g_model_data_len = %d;\n" % len(data))
print("wrote %d bytes model" % len(data))
