#!/usr/bin/env python3
"""
Generate a tiny but VALID int8 TFLite autoencoder PLACEHOLDER so the firmware
builds and runs before the real model from ../training is copied in.

It writes the SAME files / symbols that ../training/scripts/convert_tflite.py
exports, so the real files are a pure drop-in replacement:
  include/model_data.h    g_model_data[], g_model_data_len
  src/model_data.cc       16-byte aligned flatbuffer array
  include/model_config.h  kNumFeatures, kFeatureMean/Std/Clip, kInput*/kOutput*,
                          kAnomalyThreshold, kTensorArenaSize, kSampleRateHz,
                          kWindowSize, kWindowStep, kTempAlarmC
                          (+ MODEL_IS_PLACEHOLDER 1, only in the placeholder)
  models/placeholder_model.tflite

Features: 12, identical formulas/order to ../training/scripts/features.py.
Trained on SIMULATED normal driving only -> for bring-up/testing, not detection.
Usage:  python tools/make_placeholder_model.py   (needs tensorflow, numpy)
"""
import os
import numpy as np
import tensorflow as tf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS, WIN, STEP = 100, 100, 50
CLIP = 8.0
TEMP_ALARM_C = 60.0
NAMES = ["acc_mag_mean", "acc_mag_std", "acc_mag_max", "jerk_max",
         "gyro_mag_mean", "gyro_mag_max", "tilt_deg", "temp_mean", "temp_slope",
         "vib_mean", "vib_rms", "vib_peak"]
NF = len(NAMES)
rng = np.random.default_rng(42)


def features(acc, gyro, temp, vib, fs=FS):
    """Same math as training features.window_features for ONE window."""
    a = np.sqrt((acc ** 2).sum(1))
    w = np.sqrt((gyro ** 2).sum(1))
    m = acc.mean(0)
    tilt = np.degrees(np.arccos(np.clip(m[2] / (np.linalg.norm(m) + 1e-9), -1, 1)))
    vm = vib.mean()
    return np.array([a.mean(), a.std(), a.max(), np.abs(np.diff(a)).max() * fs,
                     w.mean(), w.max(), tilt, temp.mean(),
                     (temp[-1] - temp[0]) * fs / (len(temp) - 1),
                     vm, np.sqrt(((vib - vm) ** 2).mean()), vib.max()], np.float32)


def sim_normal():
    t = np.arange(WIN) / FS
    f = rng.uniform(0.5, 3.0)
    lin = np.stack([0.08 * np.sin(2 * np.pi * f * t) + rng.uniform(-0.25, 0.25),
                    0.08 * np.cos(2 * np.pi * f * t) + rng.uniform(-0.15, 0.15),
                    np.zeros(WIN)], 1)
    acc = lin + np.array([0, 0, 1.0]) + rng.normal(0, rng.uniform(0.01, 0.06), (WIN, 3))
    gyro = rng.normal(0, rng.uniform(0.5, 4.0), (WIN, 3)) + np.array([0, 0, rng.uniform(-15, 15)])
    t0 = rng.uniform(25, 45)
    temp = t0 + np.round(rng.uniform(-0.3, 0.3) * t / 0.0625) * 0.0625   # DS18B20 steps
    vib = np.clip(rng.uniform(0.05, 0.35) + rng.normal(0, rng.uniform(0.01, 0.08), WIN), 0, 1)
    return features(acc, gyro, temp, vib)


X = np.stack([sim_normal() for _ in range(4000)])
mean = X.mean(0).astype(np.float32)
std = X.std(0)
std[std < 1e-6] = 1.0
std = std.astype(np.float32)
Z = np.clip((X - mean) / std, -CLIP, CLIP).astype(np.float32)

tf.random.set_seed(42)
model = tf.keras.Sequential([
    tf.keras.Input(shape=(NF,)),
    tf.keras.layers.Dense(8, activation="relu"),
    tf.keras.layers.Dense(4, activation="relu"),
    tf.keras.layers.Dense(8, activation="relu"),
    tf.keras.layers.Dense(NF),
])
model.compile(optimizer="adam", loss="mse")
model.fit(Z, Z, epochs=40, batch_size=64, verbose=0)


def rep():
    for i in range(400):
        yield [Z[i:i + 1]]


conv = tf.lite.TFLiteConverter.from_keras_model(model)
conv.optimizations = [tf.lite.Optimize.DEFAULT]
conv.representative_dataset = rep
conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
conv.inference_input_type = tf.int8
conv.inference_output_type = tf.int8
tfl = conv.convert()
os.makedirs(os.path.join(ROOT, "models"), exist_ok=True)
open(os.path.join(ROOT, "models", "placeholder_model.tflite"), "wb").write(tfl)

it = tf.lite.Interpreter(model_content=tfl)
it.allocate_tensors()
inp, outp = it.get_input_details()[0], it.get_output_details()[0]
si, zi = inp["quantization"]
so, zo = outp["quantization"]
errs = []
for z in Z[:1000]:
    q = np.clip(np.round(z / si) + zi, -128, 127).astype(np.int8)[None]
    it.set_tensor(inp["index"], q)
    it.invoke()
    y = (it.get_tensor(outp["index"]).astype(np.float32)[0] - zo) * so
    errs.append(float(((y - z) ** 2).mean()))
thr = 1.5 * float(np.percentile(errs, 99))   # extra margin: placeholder only
print("placeholder: %d bytes, int8 score mean %.4f, threshold %.4f" % (len(tfl), np.mean(errs), thr))

# ---- model_data.h / .cc (same symbols as training export) ----
open(os.path.join(ROOT, "include", "model_data.h"), "w", newline="\n").write(
    "// PLACEHOLDER generated by tools/make_placeholder_model.py.\n"
    "// Replace with ../training/models/autoencoder/model_data.h (same symbols).\n"
    "#ifndef ACCIDENT_MODEL_DATA_H_\n#define ACCIDENT_MODEL_DATA_H_\n\n"
    "extern const unsigned char g_model_data[];\n"
    "extern const unsigned int g_model_data_len;\n\n#endif  // ACCIDENT_MODEL_DATA_H_\n")
rows = ["  " + ", ".join("0x%02x" % b for b in tfl[i:i + 12]) + ","
        for i in range(0, len(tfl), 12)]
open(os.path.join(ROOT, "src", "model_data.cc"), "w", newline="\n").write(
    "// PLACEHOLDER generated by tools/make_placeholder_model.py (%d bytes).\n"
    "#include \"model_data.h\"\n\nalignas(16) const unsigned char g_model_data[] = {\n%s\n};\n"
    "const unsigned int g_model_data_len = %d;\n" % (len(tfl), "\n".join(rows), len(tfl)))


def farr(v):
    return "{" + ", ".join("%.8gf" % x for x in v) + "}"


names = "\n".join("//   [%2d] %s" % (i, n) for i, n in enumerate(NAMES))
cfg = f"""// PLACEHOLDER generated by tools/make_placeholder_model.py - NOT a trained model.
// Replace with ../training/models/autoencoder/model_config.h (same symbols).
#ifndef ACCIDENT_MODEL_CONFIG_H_
#define ACCIDENT_MODEL_CONFIG_H_

#include <stdint.h>

#define MODEL_IS_PLACEHOLDER 1   // not present in the real exported file

// ---- sampling / windowing ----
constexpr int kSampleRateHz = {FS};
constexpr int kWindowSize = {WIN};
constexpr int kWindowStep = {STEP};
constexpr float kTempAlarmC = {TEMP_ALARM_C:.1f}f;

// ---- features (same order as training) ----
constexpr int kNumFeatures = {NF};
{names}

// z[i] = clamp((x[i] - kFeatureMean[i]) / kFeatureStd[i], -kFeatureClip, kFeatureClip)
constexpr float kFeatureClip = {CLIP:.1f}f;
static const float kFeatureMean[kNumFeatures] = {farr(mean)};
static const float kFeatureStd[kNumFeatures]  = {farr(std)};

// ---- int8 quantization ----
constexpr float kInputScale = {si:.8g}f;
constexpr int32_t kInputZeroPoint = {zi};
constexpr float kOutputScale = {so:.8g}f;
constexpr int32_t kOutputZeroPoint = {zo};

// ---- autoencoder ----
#define ACCIDENT_MODEL_AUTOENCODER 1
constexpr float kAnomalyThreshold = {thr:.8g}f;
constexpr float kAnomalyThresholdFloat = {thr:.8g}f;
constexpr float kThresholdPercentile = 99.0f;

// ---- TFLite Micro ----
constexpr int kTensorArenaSize = 8192;

#endif  // ACCIDENT_MODEL_CONFIG_H_
"""
open(os.path.join(ROOT, "include", "model_config.h"), "w", newline="\n").write(cfg)
